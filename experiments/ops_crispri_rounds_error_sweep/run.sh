#!/usr/bin/env bash
# =============================================================================
# Fig 3c: Weissman CRISPRi sequencing-rounds x error-rate sweep. 18 points
# (rounds 8-13 x symmetric epsilon 0.03/0.05/0.10), 5 trials each.
# run_benchmark.py per point (DUET 31-lambda sweep + Feldman + Sivanandan + max
# activity), then visualize_sweep.py (epsilon x rounds heatmaps, including the
# two Fig 3c panels, and the reference check against ops_crispri_symmetric).
#
# Source bundle: scripts/benchmark/archive/08-20-2026/robustness_sweep/ (its
# 2026-09-02 run). The 18 <stem>.yaml configs are generated by make_configs.py.
#
# Activate an env whose `duet` resolves to this repo first (checked below). The
# Feldman baseline shells out to the conda env named by `feldman.conda_env` in
# the configs (`ops`). Works from any cwd. Points run one after another: each
# uses all four GPUs for its PEP build and ground truth, and 31 CPU workers for
# the lambda sweep.
#   bash experiments/ops_crispri_rounds_error_sweep/run.sh
#   SWEEP_POINTS="sr10_eps0.10 sr08_eps0.03" bash .../run.sh   # a subset, in grid order
#   SKIP_COMPLETE=1 bash .../run.sh      # resume: skip points already complete (see below)
#   VARIANT=smoke bash .../run.sh        # the three <stem>.smoke.yaml configs (written
#                                        # by `python make_configs.py --smoke`)
# A point counts as complete when <outdir>/config.yaml is a byte copy of its
# config (the runner copies it after writing results.csv) and results.csv has
# every configured method in every trial. Without SKIP_COMPLETE=1 every
# selected point is re-run.
#
# A failed point does not stop the sweep: the points are independent, so every
# selected point runs, the failed ones are recorded, and the visualizer still
# renders whatever exists. The script then exits 1 if any point failed, else
# with the visualizer's exit code (1 on a Tier A reference-check failure). A
# signal (Ctrl-C, SIGTERM, SIGHUP) stops the whole sweep at once.
#
# Run after experiments/ops_crispri_symmetric: the visualizer checks this sweep's
# rounds-10 points against its outputs (and skips the check if they are absent).
#
# Outputs: <outdir>/ per point (results/experiments/ops_crispri_rounds_error_sweep/
# <stem>/) and sweep_figures/ beside them; logs: logs/<stem>.{raw.log,log} and
# logs/visualize.log there. PEP cache and scratch: the configs' cache_dir and
# scratch_dir, shared by all points. TMPDIR is pointed at <scratch_dir>/tmp so
# the Feldman runner's temporary files stay under results/ too.
# =============================================================================
set -euo pipefail

HERE="$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")"
REPO_ROOT="$(dirname "$(dirname "$HERE")")"
SFX="${VARIANT:+.$VARIANT}"
export PYTHONUNBUFFERED=1
# A signal stops the sweep, not just the running point (bash runs the trap
# once the running command has returned).
for sig in INT TERM HUP; do
    # shellcheck disable=SC2064
    trap "echo \"=== ops_crispri_rounds_error_sweep: interrupted by SIG$sig === \$(date)\" >&2; exit \$((128 + $(kill -l $sig)))" "$sig"
done

clean_log() {
    sed 's/\r$//' "$1" | sed $'s/.*\r//' | sed 's/\x1b\[[0-9;]*[a-zA-Z]//g' | tail -n +2 | head -n -1 > "$2"
}
yaml_get() {  # $1 config, $2 dotted key; fails if the key is missing or null
    python -c 'import sys, yaml; d = yaml.safe_load(open(sys.argv[1]))
for k in sys.argv[2].split("."): d = d[k]
sys.exit(f"{sys.argv[2]} is null in {sys.argv[1]}") if d is None else print(d)' "$1" "$2"
}
check_duet() {  # the active env must import duet from this repo's src/duet/
    python -c 'import sys, pathlib, duet; p = pathlib.Path(duet.__file__).resolve(); r = pathlib.Path(sys.argv[1]).resolve()
sys.exit(0 if r in p.parents else f"ERROR: the active env imports duet from {p}, not from {r}")' "$REPO_ROOT/src/duet"
}
point_complete() {  # $1 config, $2 outdir: a finished run of exactly this config is there
    python -c 'import sys, pathlib, pandas as pd, yaml
cfg, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
snap, res = out / "config.yaml", out / "results.csv"
if not (snap.is_file() and res.is_file() and snap.read_bytes() == cfg.read_bytes()): sys.exit(1)
c = yaml.safe_load(cfg.read_text())
methods = {f"DUET (lambda={x:.2f})" for x in c["duet"]["optimizer"]["lambda"]} | {"Maximum activity"}
methods |= {f"Sivanandan et al. (ED={e})" for e in c.get("sivanandan", {}).get("edit_distances", [])}
methods |= {f"Feldman et al. (ED={e})" for e in c.get("feldman", {}).get("edit_distances", [])}
got = set(map(tuple, pd.read_csv(res, usecols=["Method", "Trial"]).drop_duplicates().values.tolist()))
sys.exit(0 if {(m, t) for m in methods for t in range(1, c["trials"] + 1)} <= got else 1)' "$1" "$2"
}

cd "$HERE"
# Points: every <stem><SFX>.yaml here, in grid order, or the SWEEP_POINTS subset.
ALL=()
for f in sr[0-9][0-9]_eps[0-9].[0-9][0-9]"$SFX".yaml; do
    [[ -f "$f" ]] && ALL+=("${f%"$SFX".yaml}")
done
[[ ${#ALL[@]} -gt 0 ]] || { echo "ERROR: no sr*$SFX.yaml configs in $HERE (the smoke configs are rewritten by python make_configs.py --smoke)" >&2; exit 1; }
if [[ -n "${VARIANT:-}" ]]; then
    : # the variant's configs, whatever subset exists
elif [[ ${#ALL[@]} -ne 18 ]]; then
    echo "ERROR: expected the 18 committed configs in $HERE, found ${#ALL[@]} (python make_configs.py --check)" >&2; exit 1
fi
if [[ -n "${SWEEP_POINTS:-}" ]]; then
    POINTS=()
    for want in $SWEEP_POINTS; do
        [[ " ${ALL[*]} " == *" $want "* ]] || { echo "ERROR: unknown point '$want' (have: ${ALL[*]})" >&2; exit 1; }
    done
    for stem in "${ALL[@]}"; do [[ " $SWEEP_POINTS " == *" $stem "* ]] && POINTS+=("$stem"); done
else
    POINTS=("${ALL[@]}")
fi

check_duet
# All points share one results directory (<base>/<stem>), cache_dir and scratch_dir.
FIRST_OUT="$(realpath -m "$(yaml_get "${ALL[0]}$SFX.yaml" outdir)")"
EXP_OUT="$(dirname "$FIRST_OUT")"
SCRATCH="$(realpath -m "$(yaml_get "${ALL[0]}$SFX.yaml" scratch_dir)")"
for stem in "${ALL[@]}"; do
    out="$(realpath -m "$(yaml_get "$stem$SFX.yaml" outdir)")"
    scr="$(realpath -m "$(yaml_get "$stem$SFX.yaml" scratch_dir)")"
    [[ "$out" == "$EXP_OUT/$stem" && "$scr" == "$SCRATCH" ]] || {
        echo "ERROR: $stem$SFX.yaml: outdir must be $EXP_OUT/$stem and scratch_dir $SCRATCH" >&2; exit 1; }
done
LOGDIR="$EXP_OUT/logs"
mkdir -p "$LOGDIR" "$SCRATCH/tmp"
export TMPDIR="$SCRATCH/tmp"

echo "=== ops_crispri_rounds_error_sweep (suffix '${SFX}') === started $(date)"
echo "Points (${#POINTS[@]}): ${POINTS[*]}"
nvidia-smi --query-gpu=index,name,memory.used --format=csv || echo "WARNING: nvidia-smi unavailable; configs request device=gpu:all"

FAILED=() SKIPPED=() DONE=()
for stem in "${POINTS[@]}"; do
    CONFIG="$stem$SFX.yaml"
    if [[ "${SKIP_COMPLETE:-0}" == 1 ]] && point_complete "$CONFIG" "$EXP_OUT/$stem"; then
        echo "=== $stem: complete, skipped (SKIP_COMPLETE=1) === $(date)"
        SKIPPED+=("$stem")
        continue
    fi
    echo "=== $stem === started $(date)"
    rc=0
    script -qefc "python \"$REPO_ROOT/scripts/benchmark/run_benchmark.py\" --config \"$CONFIG\" -vv" "$LOGDIR/$stem.raw.log" || rc=$?
    clean_log "$LOGDIR/$stem.raw.log" "$LOGDIR/$stem.log" || echo "WARNING: could not write $LOGDIR/$stem.log" >&2
    if [[ $rc -eq 0 ]]; then
        DONE+=("$stem")
        echo "=== $stem === finished $(date)"
    else
        FAILED+=("$stem")
        echo "=== $stem === FAILED (exit $rc) $(date); log $LOGDIR/$stem.log; carrying on with the other points" >&2
    fi
done

echo "=== Sweep visualization === $(date)"
VIS_RC=0
{
    if [[ ${#FAILED[@]} -gt 0 ]]; then
        echo "WARNING: these points failed in this run: ${FAILED[*]}. Their cells, if any, come from"
        echo "results already on disk before this run; do not trust them."
    fi
    python "$HERE/visualize_sweep.py" --variant "${VARIANT:-}"
} 2>&1 | tee "$LOGDIR/visualize.log" || VIS_RC=$?

echo "=== ops_crispri_rounds_error_sweep === finished $(date)"
echo "Summary: ${#POINTS[@]} selected; ${#DONE[@]} ran ok; ${#SKIPPED[@]} skipped as complete; ${#FAILED[@]} failed${FAILED[*]:+ (${FAILED[*]})}; visualizer exit $VIS_RC"
echo "Outputs: $EXP_OUT"
echo "Fig 3c panels: $EXP_OUT/sweep_figures/heatmap_maximum_activity_mean_decode_accuracy_10th_percentile.svg (top)"
echo "               $EXP_OUT/sweep_figures/heatmap_maximum_activity_standard_deviation_decode_accuracy.svg (bottom)"
if [[ ${#FAILED[@]} -gt 0 ]]; then
    echo "ERROR: ${#FAILED[@]} point(s) failed: ${FAILED[*]}. Re-run them with SWEEP_POINTS=\"${FAILED[*]}\" (or SKIP_COMPLETE=1)." >&2
    exit 1
fi
if [[ $VIS_RC -ne 0 ]]; then
    echo "ERROR: visualize_sweep.py exited $VIS_RC (see $LOGDIR/visualize.log; a Tier A REFERENCE CHECK FAILED exits 1 after all figures are written)" >&2
fi
exit "$VIS_RC"
